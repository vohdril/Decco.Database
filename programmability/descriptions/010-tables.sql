 N'SCOPED WORK. Investigation, research or suppression (Cat_OperationType) conducted INSIDE a facility — FacilityId is mandatory from creation. Unlike Anomaly, which is a global catalog, an operation belongs to a place, so it is the first entity whose access and cache are sliced by facility (keys decco:inst:{codigo}:operacao:*).';

