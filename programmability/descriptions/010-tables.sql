EXEC dbo.usp_Decco_SetDescription 'Anomaly', NULL,
 N'ROOT ENTITY. Each row is a record of the DeCCO anomaly catalog. It gathers the ontological classification (class, layer, matter, mechanisms), the Brazilian classification (cognition, dangerousness), the measurable Theta markers and the operational state. Id starts at 1000; the public identity is ScpCode.';

