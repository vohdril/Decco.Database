EXEC dbo.usp_Decco_SetDescription 'AnomalyEvent', NULL,
 N'1:N INSTANCE of Anomaly. The manifestation as an occurrence in time: window, periodicity, affected zone and trigger preconditions.';

-- ── Configuration / back office ─────────────────────────────────────────────

EXEC dbo.usp_Decco_SetDescription 'Facility', NULL,
 N'CONFIGURATION / SCOPE. A physical DeCCO place: site, laboratory, containment area or forward post (Cat_FacilityType). Two-level hierarchy — site at the root, the other types as children (TR_Facility_ValidateHierarchy). It is the PERMISSION BOUNDARY of the system: the user gets a list of facilities (a relation that lives in DeccoAuthDB) and the scoped work (Operation) is filtered by it. Absorbed the former Laboratorio table (migrations 0002/0004).';

