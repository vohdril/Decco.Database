EXEC dbo.usp_Decco_SetDescription 'Protocol_AppliedTo', NULL,
 N'N:N RELATIONSHIP between ContainmentProtocol and Anomaly, with a validity window (start/end) and status. Answers: which protocols are active on this anomaly, and since when.';

EXEC dbo.usp_Decco_SetDescription 'AnomalyNotification', NULL,
 N'FIELD INPUT. Report of a phenomenon not yet cataloged, with location, priority and reporter. AnomalyId is null until the investigation concludes — it is the entry point of the funnel that ends in a catalog record.';

